-- Exam writes go through ownership-checked RPCs. Public tables are read-only.
create schema if not exists private;
create table private.exam_pool (
  question_key smallint primary key references public.question_catalog(question_key),
  exam smallint not null check (exam in (1,2)),
  area text not null,
  domain smallint not null check (domain between 1 and 10),
  correct_mask smallint not null check (correct_mask between 0 and 31)
);
revoke all on private.exam_pool from public, anon, authenticated;

create table public.user_exam_sessions (
  id uuid primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exam smallint not null check (exam in (1,2)),
  started_at timestamptz not null default now(),
  deadline timestamptz not null default (now() + interval '90 minutes'),
  submitted_at timestamptz,
  revision integer not null default 0,
  unique(user_id, id),
  check (deadline = started_at + interval '90 minutes'),
  check (submitted_at is null or submitted_at between started_at and deadline)
);
create index user_exam_sessions_owner_time on public.user_exam_sessions(user_id, started_at desc, id);
create unique index user_exam_sessions_one_active on public.user_exam_sessions(user_id) where submitted_at is null;
create table public.user_exam_questions (
  session_id uuid not null,
  user_id uuid not null,
  question_key smallint not null references public.question_catalog(question_key),
  position smallint not null check (position between 0 and 39),
  statement_order smallint[] not null check (array_length(statement_order,1) = 5 and statement_order @> array[0,1,2,3,4]::smallint[]),
  answer_mask smallint not null default 0 check (answer_mask between 0 and 31),
  answered_mask smallint not null default 0 check (answered_mask between 0 and 31),
  pinned boolean not null default false,
  attempt_id uuid not null default gen_random_uuid(),
  primary key(session_id, question_key),
  unique(session_id, position),
  unique(attempt_id),
  foreign key(user_id, session_id) references public.user_exam_sessions(user_id, id) on delete cascade,
  check ((answer_mask & answered_mask) = answer_mask)
);
create index user_exam_questions_owner on public.user_exam_questions(user_id);
create index user_exam_questions_key on public.user_exam_questions(question_key);
alter table public.user_question_attempts
  add column exam_session_id uuid,
  add column answered_mask smallint not null default 31 check (answered_mask between 0 and 31),
  add constraint attempts_exam_session_fk foreign key (user_id, exam_session_id) references public.user_exam_sessions(user_id,id),
  add constraint attempts_exam_source_check check (exam_session_id is null or source = 'exam'),
  add constraint attempts_classification_check check ((answer_mask & answered_mask) = answer_mask);
create unique index attempts_exam_question on public.user_question_attempts(exam_session_id, question_key) where exam_session_id is not null;
-- Only the finalization transaction can insert or delete linked exam attempts.
alter policy "Users can insert their own answer attempts" on public.user_question_attempts
  with check ((select auth.uid()) = user_id and exam_session_id is null);
alter policy "Users can delete their own answer attempts" on public.user_question_attempts
  using ((select auth.uid()) = user_id and exam_session_id is null);

alter table public.user_exam_sessions enable row level security;
alter table public.user_exam_questions enable row level security;
create policy "Owners read exam sessions" on public.user_exam_sessions for select to authenticated using ((select auth.uid()) = user_id);
create policy "Owners read exam questions" on public.user_exam_questions for select to authenticated using ((select auth.uid()) = user_id);
revoke all on public.user_exam_sessions, public.user_exam_questions from public, anon, authenticated;
grant select on public.user_exam_sessions, public.user_exam_questions to authenticated;

-- Snapshot reads final classifications and scores from attempts after submission.
create function private.exam_snapshot(p_session uuid) returns jsonb
language sql stable security invoker set search_path = '' as $$
  select jsonb_build_object(
    'id',s.id,'exam',s.exam,'started_at',s.started_at,'deadline',s.deadline,
    'submitted_at',s.submitted_at,'revision',s.revision,'server_now',now(),
    'items',(select jsonb_agg(jsonb_build_object(
      'question_key',q.question_key,'position',q.position,'statement_order',q.statement_order,
      'answer_mask',case when s.submitted_at is null then q.answer_mask else a.answer_mask end,
      'answered_mask',case when s.submitted_at is null then q.answered_mask else a.answered_mask end,
      'pinned',q.pinned,'score',a.score
    ) order by q.position) from public.user_exam_questions q
      left join public.user_question_attempts a on a.exam_session_id=q.session_id and a.question_key=q.question_key
      where q.session_id=s.id)
  ) from public.user_exam_sessions s where s.id=p_session and s.user_id=(select auth.uid());
$$;

create function private.start_practice_exam(p_exam integer, p_request_id uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_user uuid := auth.uid(); v_id uuid; v_started timestamptz := clock_timestamp();
begin
  if v_user is null then raise exception 'Sign in to start an exam' using errcode='42501'; end if;
  if p_exam not in (1,2) or p_exam is null or p_request_id is null then raise exception 'Invalid exam'; end if;
  -- Serialize concurrent starts for this account and make an uncertain start retry safe.
  perform pg_advisory_xact_lock(hashtextextended(v_user::text,0));
  select id into v_id from public.user_exam_sessions where user_id=v_user and (id=p_request_id or submitted_at is null)
    order by (id=p_request_id) desc limit 1;
  if v_id is not null then return private.exam_snapshot(v_id); end if;
  if exists(select 1 from public.user_exam_sessions where id=p_request_id) then raise exception 'Invalid request id'; end if;
  insert into public.user_exam_sessions(id,user_id,exam,started_at,deadline)
    values(p_request_id,v_user,p_exam,v_started,v_started+interval '90 minutes');
  insert into public.user_exam_questions(session_id,user_id,question_key,position,statement_order)
    select p_request_id,v_user,question_key,(row_number() over(order by random())-1)::smallint,
      (select array_agg(n order by random()) from generate_series(0,4) n where question_key is not null)::smallint[]
    from (select question_key,row_number() over(partition by area,domain order by random()) as rank
      from private.exam_pool where exam=p_exam) sampled where rank<=2;
  if (select count(*) from public.user_exam_questions where session_id=p_request_id) <> 40 then raise exception 'Incomplete exam pool'; end if;
  return private.exam_snapshot(p_request_id);
end;
$$;

create table private.exam_sync_receipts (
  session_id uuid references public.user_exam_sessions(id) on delete cascade,
  request_id uuid not null,
  primary key(session_id, request_id)
);
revoke all on private.exam_sync_receipts from public, anon, authenticated;

create function private.sync_practice_exam(p_session uuid, p_revision integer, p_edits jsonb, p_submitted_at timestamptz, p_request_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_session public.user_exam_sessions; v_edit jsonb; v_q public.user_exam_questions; v_bit integer; v_time timestamptz;
begin
  if auth.uid() is null then raise exception 'Sign in to sync this exam' using errcode='42501'; end if;
  select * into v_session from public.user_exam_sessions where id=p_session and user_id=auth.uid() for update;
  if not found then raise exception 'Exam not found' using errcode='42501'; end if;
  if p_request_id is null then raise exception 'Missing request id'; end if;
  if exists(select 1 from private.exam_sync_receipts where session_id=p_session and request_id=p_request_id) then return private.exam_snapshot(p_session) || '{"acknowledged":true}'::jsonb; end if;
  if v_session.submitted_at is not null then return private.exam_snapshot(p_session) || '{"finalizedElsewhere":true}'::jsonb; end if;
  if p_revision is distinct from v_session.revision then
    return private.exam_snapshot(p_session) || '{"conflict":true}'::jsonb;
  end if;
  if p_edits is null or jsonb_typeof(p_edits)<>'array' or jsonb_array_length(p_edits)>1000 then raise exception 'Invalid edits'; end if;
  if p_submitted_at is not null and (p_submitted_at < v_session.started_at or p_submitted_at > least(v_session.deadline,clock_timestamp()+interval '10 seconds')) then raise exception 'Invalid submission time'; end if;
  for v_edit in select value from jsonb_array_elements(p_edits) loop
    v_time := (v_edit->>'at')::timestamptz;
    if v_time is null or v_time < v_session.started_at or v_time > least(v_session.deadline,coalesce(p_submitted_at,v_session.deadline),clock_timestamp()+interval '10 seconds') then raise exception 'Edit outside exam time'; end if;
    select * into v_q from public.user_exam_questions where session_id=p_session and position=(v_edit->>'position')::integer;
    if not found then raise exception 'Invalid question'; end if;
    if v_edit->>'kind'='answer' then
      if (v_edit->>'statement')::integer not between 0 and 4 or not (v_edit ? 'value') or jsonb_typeof(v_edit->'value') not in ('boolean','null') then raise exception 'Invalid classification'; end if;
      v_bit := 1 << (v_edit->>'statement')::integer;
      update public.user_exam_questions set
        answer_mask = (answer_mask & ~v_bit) | (case when v_edit->>'value'='true' then v_bit else 0 end),
        answered_mask = (answered_mask & ~v_bit) | (case when v_edit->'value'='null'::jsonb then 0 else v_bit end)
        where session_id=p_session and question_key=v_q.question_key;
    elsif v_edit->>'kind'='pin' and jsonb_typeof(v_edit->'value')='boolean' then
      update public.user_exam_questions set pinned=(v_edit->>'value')::boolean where session_id=p_session and question_key=v_q.question_key;
    else raise exception 'Invalid edit'; end if;
  end loop;
  -- Finalize only after the client has drained all pre-deadline queued edits.
  if p_submitted_at is not null then
    v_time := coalesce(p_submitted_at,v_session.deadline);
    insert into public.user_question_attempts(user_id,attempt_id,question_key,answer_mask,answered_mask,score,source,skipped,answered_at,exam_session_id)
      select v_session.user_id,q.attempt_id,q.question_key,q.answer_mask,q.answered_mask,
        bit_count(((~(q.answer_mask # k.correct_mask)) & q.answered_mask)::integer::bit(5)),
        'exam',false,v_time,p_session
      from public.user_exam_questions q join private.exam_pool k using(question_key) where q.session_id=p_session;
    update public.user_exam_sessions set submitted_at=v_time where id=p_session;
    -- Draft values no longer duplicate the final answer history.
    update public.user_exam_questions set answer_mask=0,answered_mask=0 where session_id=p_session;
  end if;
  update public.user_exam_sessions set revision=revision+1 where id=p_session;
  insert into private.exam_sync_receipts(session_id,request_id) values(p_session,p_request_id);
  return private.exam_snapshot(p_session) || '{"acknowledged":true}'::jsonb;
end;
$$;

-- Exposed entry points run as the caller; privileged code lives in private,
-- fixes its search_path, checks auth.uid(), and accepts no user_id or score.
create function public.start_practice_exam(p_exam integer,p_request_id uuid) returns jsonb
language sql security invoker set search_path = '' as $$ select private.start_practice_exam(p_exam,p_request_id); $$;
