-- Upgrade account-scoped v1 local exams without discarding their questions,
-- original deadline, or history. Scores are always recomputed by the database.
create function private.import_practice_exam(p_session uuid,p_exam integer,p_started_at timestamptz,p_submitted_at timestamptz,p_items jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_row jsonb; v_position integer:=0; v_edits jsonb:='[]'; v_n integer; v_finish timestamptz;
begin
  if v_user is null then raise exception 'Sign in to import exams' using errcode='42501'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_user::text,0));
  if exists(select 1 from public.user_exam_sessions where id=p_session and user_id=v_user) then return private.exam_snapshot(p_session); end if;
  if p_exam not in (1,2) or p_exam is null or p_started_at is null or p_started_at>clock_timestamp()+interval '10 seconds' or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)<>40 then raise exception 'Invalid legacy exam'; end if;
  if p_submitted_at is not null and p_submitted_at>clock_timestamp()+interval '10 seconds' then raise exception 'Invalid legacy submission time'; end if;
  if exists(select 1 from jsonb_array_elements(p_items) j where jsonb_typeof(j.value->'answers')<>'array' or jsonb_array_length(j.value->'answers')<>5 or jsonb_typeof(j.value->'pinned')<>'boolean') then raise exception 'Invalid legacy answers'; end if;
  if exists(select 1 from jsonb_array_elements(p_items) j cross join lateral jsonb_array_elements(j.value->'answers') a where jsonb_typeof(a.value) not in ('boolean','null')) then raise exception 'Invalid legacy classification'; end if;
  if (select count(distinct (value->>'question_key')::integer) from jsonb_array_elements(p_items))<>40 then raise exception 'Duplicate legacy questions'; end if;
  if (select count(*) from jsonb_array_elements(p_items) j join private.exam_pool p on p.question_key=(j.value->>'question_key')::integer where p.exam=p_exam)<>40 then raise exception 'Invalid legacy question pool'; end if;
  if exists(select 1 from jsonb_array_elements(p_items) j join private.exam_pool p on p.question_key=(j.value->>'question_key')::integer group by p.area,p.domain having count(*)<>2) then raise exception 'Invalid legacy domains'; end if;
  v_finish:=coalesce(p_submitted_at,case when clock_timestamp()>=p_started_at+interval '90 minutes' then p_started_at+interval '90 minutes' else null end);
  -- Closed imports can coexist with an active exam. The placeholder is replaced
  -- inside this transaction before it is visible or any attempts are inserted.
  insert into public.user_exam_sessions(id,user_id,exam,started_at,deadline,submitted_at)
    values(p_session,v_user,p_exam,p_started_at,p_started_at+interval '90 minutes',v_finish);
  for v_row in select value from jsonb_array_elements(p_items) loop
    insert into public.user_exam_questions(session_id,user_id,question_key,position,statement_order)
    values(p_session,v_user,(v_row->>'question_key')::smallint,v_position,array(select value::smallint from jsonb_array_elements_text(v_row->'order')));
    for v_n in 0..4 loop
      if v_row->'answers'->v_n is distinct from 'null'::jsonb then
        v_edits:=v_edits||jsonb_build_array(jsonb_build_object('position',v_position,'kind','answer','statement',v_n,'value',v_row->'answers'->v_n,'at',p_started_at));
      end if;
    end loop;
    v_edits:=v_edits||jsonb_build_array(jsonb_build_object('position',v_position,'kind','pin','value',v_row->'pinned','at',p_started_at));
    v_position:=v_position+1;
  end loop;
  if v_finish is not null then
    -- Import final values directly to avoid violating the one-active-session
    -- index while an unrelated, current exam is running.
    for v_row in select value from jsonb_array_elements(p_items) loop
      insert into public.user_question_attempts(user_id,attempt_id,question_key,answer_mask,answered_mask,score,source,skipped,answered_at,exam_session_id)
      select v_user,q.attempt_id,q.question_key,m.true_mask,m.answered_mask,
        bit_count(((~(m.true_mask # p.correct_mask)) & m.answered_mask)::integer::bit(5)),
        'exam',false,v_finish,p_session
      from public.user_exam_questions q join private.exam_pool p using(question_key)
      cross join lateral(select coalesce(sum(case when v_row->'answers'->n='true'::jsonb then 1<<n else 0 end),0)::smallint as true_mask,
        coalesce(sum(case when jsonb_typeof(v_row->'answers'->n)='boolean' then 1<<n else 0 end),0)::smallint as answered_mask from generate_series(0,4)n) m
      where q.session_id=p_session and q.question_key=(v_row->>'question_key')::smallint;
      update public.user_exam_questions set pinned=(v_row->>'pinned')::boolean where session_id=p_session and question_key=(v_row->>'question_key')::smallint;
    end loop;
    update public.user_exam_sessions set revision=1 where id=p_session;
    return private.exam_snapshot(p_session);
  end if;
  return private.sync_practice_exam(p_session,0,v_edits,null,gen_random_uuid());
end;
$$;
create function public.import_practice_exam(p_session uuid,p_exam integer,p_started_at timestamptz,p_submitted_at timestamptz,p_items jsonb)
returns jsonb language sql security invoker set search_path='' as $$ select private.import_practice_exam(p_session,p_exam,p_started_at,p_submitted_at,p_items); $$;
revoke all on function private.import_practice_exam(uuid,integer,timestamptz,timestamptz,jsonb),public.import_practice_exam(uuid,integer,timestamptz,timestamptz,jsonb) from public,anon;
