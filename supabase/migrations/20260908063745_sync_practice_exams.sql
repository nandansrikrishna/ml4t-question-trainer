language sql stable security invoker set search_path = '' as $$ select private.exam_snapshot(p_session); $$;
revoke all on function private.exam_snapshot(uuid), private.start_practice_exam(integer,uuid), private.sync_practice_exam(uuid,integer,jsonb,timestamptz,uuid) from public, anon;
